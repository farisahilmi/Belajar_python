import math

# Operasi akar dan pangkat
print("Akar kuadrat 16:", math.sqrt(16))    # 4.0
print("Akar kubik 8:", math.pow(8, 1/3))    # 2.0
print("2 pangkat 10:", math.pow(2, 10))     # 1024.0

# Pembulatan
print("Ceiling 4.2:", math.ceil(4.2))       # 5
print("Floor 4.8:", math.floor(4.8))        # 4

# Logaritma
print("Log natural 10:", math.log(10))      # 2.302...
print("Log basis 10:", math.log10(100))     # 2.0