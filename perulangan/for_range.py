# mencetak angka 0 sampai 4
for i in range(5):
    print(i)

print("\n") # sebagai penanda tab doang


# mencetak angka 1 sampai 5
for i in range(1, 6):
    print(i)


print("\n")

# mencetak "Hello" sebanyak 3 kali
for i in range(3):
    print("Hello")

print("\n")

# menghitung mundur
print("Menghitung muncur: ")
for i in range(5, 0, -1): # metode looping 3s (start, stop, step)
    print(i)